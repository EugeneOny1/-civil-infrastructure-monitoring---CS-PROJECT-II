"""
Database Inspection and Cleanup Script for Infrastructure Reports.
Identifies excessive synthetic test records generated by repeated test runs,
preserving all legitimate user reports, canonical seed reports, and 1 baseline instance of each test scenario.
"""
import sys
import os
from pathlib import Path

# Setup paths
BASE_DIR = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(BASE_DIR))

from app.services.database import db_service

LEGITIMATE_REPORT_IDS = {
    'REP-2026-0001',                            # Canonical seed report
    '8a4810bb-4114-41b2-870d-f43c52bebb1d',    # User report - Waiyaki Way
    '9a2fae3f-f756-4c3c-ab0a-7d352cbd42df',    # User report - Waiyaki Way
    '42ce53c9-b701-47e8-8e34-7d21a838a5c4',    # User report - Ole Sangale Rd
    '936465c0-458f-4950-b5c1-5bbdb0cafbd5',    # User report - Kenyatta Avenue
    '3d679229-0c8f-4522-8b8f-bc2625dcbe82',    # User report - Harambee Avenue
    'c5f1920c-67b5-4674-951f-7393bc6bb6d4',    # Tag Location verification report
}

BASELINE_TEST_SCENARIOS = {
    '03f79869-ea41-4af7-a2ef-c6e8f601a228',    # Baseline test defect submission
    'f39e21a1-fe46-47bb-a31a-d3013aefbd43',    # Baseline unusual pairing test
    '076f20fa-8a36-48f8-bdde-753b1c3b60cf',    # Baseline clean surface test
    'ce95f9b5-8bc6-49e9-affd-e18407445019',    # Baseline engineer survey test
}

def analyze_reports():
    reports = db_service.find('infrastructure_reports')
    total = len(reports)
    
    legitimate = []
    baseline_tests = []
    cleanup_set = []

    for r in reports:
        rid = r.get('_id')
        if rid in LEGITIMATE_REPORT_IDS:
            legitimate.append(r)
        elif rid in BASELINE_TEST_SCENARIOS:
            baseline_tests.append(r)
        else:
            # Check if this matches one of the synthetic test loop duplicates
            desc = r.get('description', '')
            uid = r.get('user_id', '')
            if uid in ('usr_cit_01', 'usr_eng_test_author', 'test_tag_loc_citizen_id') and any(s in desc for s in ['test', 'Integration test', 'Unusual defect', 'Clean surface', 'routine civil infrastructure survey']):
                cleanup_set.append(r)
            else:
                # If in doubt, preserve as legitimate!
                legitimate.append(r)

    print("==================================================================")
    print(f"DATABASE INSPECTION SUMMARY (Total Reports: {total})")
    print("==================================================================")
    print(f"Legitimate Reports to Retain: {len(legitimate)}")
    for r in legitimate:
        loc = r.get('location') or r.get('metadata', {}).get('location_name', 'Unknown')
        print(f"  - [{r.get('_id')}] {loc} | User: {r.get('user_id')} | {r.get('description')[:45]}")
    
    print(f"\nBaseline Test Scenarios to Retain (1 per scenario): {len(baseline_tests)}")
    for r in baseline_tests:
        loc = r.get('location') or r.get('metadata', {}).get('location_name', 'Unknown')
        print(f"  - [{r.get('_id')}] {loc} | User: {r.get('user_id')} | {r.get('description')[:45]}")

    print(f"\nProposed Synthetic Cleanup Set (Redundant Test Duplicates): {len(cleanup_set)}")
    categories = {}
    for r in cleanup_set:
        key = (r.get('user_id'), r.get('description', '')[:35])
        categories[key] = categories.get(key, 0) + 1
    for k, cnt in categories.items():
        print(f"  - {cnt}x copies of: '{k[1]}' (User: {k[0]})")
    print("==================================================================")
    return legitimate, baseline_tests, cleanup_set

if __name__ == '__main__':
    analyze_reports()
