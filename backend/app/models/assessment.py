"""
AIAssessment model for Civil Infrastructure Monitoring System.
Stores automated inference outcomes generated by SSD-MobileNetV2.
"""

from datetime import datetime


class AIAssessment:
    """
    AIAssessment entity mapping to Database Schema.
    Stores automated inference outcomes generated by SSD-MobileNetV2.
    """
    SEVERITY_LOW = 'Low'
    SEVERITY_MODERATE = 'Moderate'
    SEVERITY_MEDIUM = 'Moderate'  # Alias for compatibility
    SEVERITY_CRITICAL = 'Critical'

    CLASS_CRACK = 'Crack'
    CLASS_POTHOLE = 'Pothole'
    CLASS_SURFACE_DETERIORATION = 'Surface deterioration'

    def __init__(self, image_id, defect_class, confidence_score, bounding_box, relative_severity,
                 detections=None, assessment_id=None, model_name='SSD-MobileNetV2',
                 model_version='ssd_mobilenet_v2_lr00125_step5000_v1', class_id=None,
                 relative_area=0.0, area_percentage=0.0, bounding_box_pixels=None,
                 validation_status='valid', validation_message='', created_at=None):
        self.assessment_id = str(assessment_id) if assessment_id else None
        self.image_id = str(image_id)
        self.defect_class = defect_class or 'None Detected'  # Primary defect category name
        self.class_name = self.defect_class
        self.class_id = class_id
        self.confidence_score = round(float(confidence_score), 4) if confidence_score is not None else 0.0
        self.confidence = self.confidence_score
        self.bounding_box = bounding_box  # [ymin, xmin, ymax, xmax] normalized (0 to 1)
        self.bounding_box_pixels = bounding_box_pixels or {}
        self.relative_severity = relative_severity or self.SEVERITY_LOW  # 'Low', 'Moderate', 'Critical'
        self.severity = self.relative_severity
        self.relative_area = round(float(relative_area), 4) if relative_area is not None else 0.0
        self.area_percentage = round(float(area_percentage), 2) if area_percentage is not None else 0.0
        self.validation_status = validation_status or 'valid'
        self.validation_message = validation_message or ''
        self.detections = detections or []  # All detected instances in the image
        self.model_name = model_name
        self.model_version = model_version
        self.created_at = created_at or datetime.utcnow().isoformat()

    def to_dict(self):
        return {
            'assessment_id': self.assessment_id,
            'image_id': self.image_id,
            'class_id': self.class_id,
            'class_name': self.class_name,
            'defect_class': self.defect_class,
            'confidence': self.confidence,
            'confidence_score': self.confidence_score,
            'confidence_percentage': round(self.confidence_score * 100, 1),
            'bounding_box': self.bounding_box,
            'bounding_box_pixels': self.bounding_box_pixels,
            'relative_severity': self.relative_severity,
            'severity': self.severity,
            'relative_area': self.relative_area,
            'area_percentage': self.area_percentage,
            'validation_status': self.validation_status,
            'validation_message': self.validation_message,
            'detections': self.detections,
            'model_name': self.model_name,
            'model_version': self.model_version,
            'created_at': self.created_at
        }

    @classmethod
    def from_dict(cls, data):
        if not data:
            return None
        return cls(
            assessment_id=data.get('_id') or data.get('assessment_id'),
            image_id=data.get('image_id'),
            defect_class=data.get('defect_class') or data.get('class_name', 'Crack'),
            confidence_score=data.get('confidence_score') or data.get('confidence', 0.0),
            bounding_box=data.get('bounding_box', [0, 0, 0, 0]),
            relative_severity=data.get('relative_severity') or data.get('severity', cls.SEVERITY_LOW),
            detections=data.get('detections', []),
            model_name=data.get('model_name', 'SSD-MobileNetV2'),
            model_version=data.get('model_version', 'ssd_mobilenet_v2_lr00125_step5000_v1'),
            class_id=data.get('class_id'),
            relative_area=data.get('relative_area', 0.0),
            area_percentage=data.get('area_percentage', 0.0),
            bounding_box_pixels=data.get('bounding_box_pixels'),
            validation_status=data.get('validation_status', 'valid'),
            validation_message=data.get('validation_message', ''),
            created_at=data.get('created_at')
        )
